bool SuperEnumConverter::ParseEnumDefinition(std::shared_ptr<StoredDocumentNode> additionalIncludeNode)
{
    auto definition = std::make_shared<EnumDefinition>();
    if (std::shared_ptr<StoredDocumentAttribute> attribute = additionalIncludeNode->Attribute("side", CaseSensitivity::IgnoreCase))
    {
        std::string sideValue = StringHelpers::ToLower(attribute->Value());
        if (sideValue == "left")
        {
            definition->IsLeft = true;
        }
        else if (sideValue == "right")
        {
            definition->IsLeft = false;
        }
    }

    if (std::shared_ptr<StoredDocumentAttribute> attribute = additionalIncludeNode->Attribute("type", CaseSensitivity::IgnoreCase))
    {
        definition->Type = attribute->Value();
    }

    if (std::shared_ptr<StoredDocumentAttribute> attribute = additionalIncludeNode->Attribute("UseTypeAsPrefix", CaseSensitivity::IgnoreCase))
    {
        std::string value = StringHelpers::ToLower(attribute->Value());
        if (value == "true")
        {
            definition->UseTypeAsPrefix = true;
        }
        else if (value == "false")
        {
            definition->UseTypeAsPrefix = false;
        }
    }

    // Do not set if there was an error.
    if (definition->Type.empty())
    {
        return false;
    }

    if (definition->IsLeft)
    {
        m_left = *definition;
    }
    else
    {
        m_right = *definition;
    }
}

std::string SuperEnumConverter::PrintIndents(int number)
{
    std::string output = "";
    for (int i = 0; i < number; ++i)
    {
        output += "    ";
    }

    return output;
}

std::string SuperEnumConverter::PrintHeader(int indents)
{
    std::string output = "";
    if (!m_header.Parsed)
    {
        return output;
    }

    std::vector<std::string> lines = StringHelpers::Split(m_header.Value, "\n");
    for (const std::string line : lines)
    {
        std::string lineTrimmed = StringHelpers::Trim(line);

        // Our standard is } on a line.
        if (lineTrimmed == "}")
        {
            --indents;
        }

        if (!lineTrimmed.empty())
        {
            output += PrintIndents(indents) + lineTrimmed + "\n";
        }

        size_t open = 0, closed = 0;
        for (size_t i = 0; i < lineTrimmed.length(); ++i)
        {
            if (lineTrimmed[i] == '{')
            {
                ++open;
            }
            else if (lineTrimmed[i] == '}')
            {
                ++closed;
            }
        }
    }

    // Any required includes would go here.
    // For this file there are none.

    output += PrintIndents(indents) + "\n";
    output += PrintIndents(indents) + "\n";

    return output;
}

std::string SuperEnumConverter::PrintFooter(int indents)
{
    std::string output = {};
    if (!m_footer.Parsed)
    {
        return output;
    }

    output = "\n";

    std::vector<std::string> lines = StringHelpers::Split(m_footer.Value, "\n");
    for (const std::string line : lines)
    {
        std::string lineTrimmed = StringHelpers::Trim(line);

        // Our standard is } on a line.
        if (lineTrimmed == "}")
        {
            --indents;
        }

        if (!lineTrimmed.empty())
        {

            output += PrintIndents(indents) + lineTrimmed + "\n";
        }

        size_t open = 0, closed = 0;
        for (size_t i = 0; i < lineTrimmed.length(); ++i)
        {
            if (lineTrimmed[i] == '{')
            {
                ++open;
            }
            else if (lineTrimmed[i] == '}')
            {
                ++closed;
            }
        }

        indents += static_cast<int>(open) - static_cast<int>(closed);
    }

    return output;
}

