SuperEnumConverter::SuperEnumConverter()
{
    m_converterType = SuperEnumConverterType::Unknown;
    m_path = {};
    m_pathPrefixToRoot = {};
}

bool SuperEnumConverter::FromString(const std::string& superEnumFile, const std::string& path)
{
    m_path = path;
    m_pathPrefixToRoot = {};
    for (size_t i = 0; i < m_path.length(); ++i)
    {
        if (m_path[i] == '\\' || m_path[i] == '/')
        {
            m_pathPrefixToRoot += "../";
        }
    }

    std::shared_ptr<StoredDocument> xml = std::make_shared<RapidXMLDocument>();
    if (!xml->Load(superEnumFile))
    {
        Log::Error("Could not parse file: " + path,
            "SuperEnumConverter::FromString(const std::string&, const std::string&)");
        return false;
    }

    std::shared_ptr<StoredDocumentNode> root = xml->GetRoot();
    if (!ParseRoot(root))
    {
        Log::Error("Could not parse root of file: " + path,
            "SuperEnumConverter::FromString(const std::string&, const std::string&)");
        return false;
    }

    std::shared_ptr<StoredDocumentNode> additionalIncludes = {};
    for (std::shared_ptr<StoredDocumentNode> child = root->GetFirstChild(); child; child = child->GetAdjacentNode())
    {
        std::string name = StringHelpers::Trim(StringHelpers::ToLower(child->Name()));
        if (name == "header")
        {
            if (!ParseHeader(child))
            {
                return false;
            }
        }
        else if (name == "namespace")
        {
            if (!ParseNamespace(child))
            {
                return false;
            }
        }
        else if (name == "enumconvertercomment")
        {
            if (!ParseEnumComment(child))
            {
                return false;
            }
        }
        else if (name == "converter")
        {
            if (!ParseConverter(child))
            {
                return false;
            }
        }
        else if (name == "additionalincludes")
        {
            additionalIncludes = child;
        }
        else if (name == "footer")
        {
            if (!ParseFooter(child))
            {
                return false;
            }
        }
        else if (name == "namespacefooter")
        {
            if (!ParseNamespaceFooter(child))
            {
                return false;
            }
        }
        else if (name == "enumdefinition")
        {
            if (!ParseEnumDefinition(child))
            {
                Log::Error("Could not parse enum definition. Path: " + m_path,
                    "SuperEnumConverter::FromString(const std::string&, const std::string&)");
                return false;
            }
        }
        //
    }

    if (additionalIncludes)
    {
        ParseAdditionalIncludes(additionalIncludes);
    }

    return true;
}

std::string SuperEnumConverter::ToString()
{
    std::string output = {};
    int indents = 0;

    output += PrintHeader(indents);
    output += "// +------------------------------+\n";
    output += "// Generated by SuperGenerator as an\n";
    output += "// SuperEnumConverter. See Tools for details.\n";
    output += "// +------------------------------+\n";

    if (m_namespace.Parsed)
    {
        output += "namespace " + m_namespace.Value + "\n";
        output += "{\n";
        ++indents;
    }

    output += PrintEnumConverter(indents);

    // This goes outside the class but in the namespace.
    output += PrintNamespaceFooter(indents);

    if (m_namespace.Parsed)
    {
        --indents;
        output += "}\n";
    }

    output += PrintFooter(indents);

    return output;

    if (m_defaultValue)
    {
        if (m_left.UseTypeAsPrefix)
        {
            output += m_left.Type + "::";
        }

        output += m_defaultValue->Left;

        output += " == ";

        if (m_right.UseTypeAsPrefix)
        {
            output += m_right.Type + "::";
        }

        output += m_defaultValue->Right;

        output += "\n";
    }

    for (const std::shared_ptr<Conversion>& conversion : m_allConversions)
    {
        if (m_left.UseTypeAsPrefix)
        {
            output += m_left.Type + "::";
        }

        output += conversion->Left;

        output += " == ";

        if (m_right.UseTypeAsPrefix)
        {
            output += m_right.Type + "::";
        }

        output += conversion->Right;

        output += "\n";
    }

    return output;
}

bool SuperEnumConverter::ParseRoot(std::shared_ptr<StoredDocumentNode> rootNode)
{
    m_converterType = SuperEnumConverterType::Standard;
    if (auto typeAttribute = rootNode->Attribute("Type", CaseSensitivity::IgnoreCase))
    {
        SuperEnumConverterType parsed = ESuperEnumConverterType::FromString(typeAttribute->Value());
        if (parsed != SuperEnumConverterType::Unknown)
        {
            m_converterType = parsed;
        }
    }

    return true;
}

bool SuperEnumConverter::ParseHeader(std::shared_ptr<StoredDocumentNode> headerNode)
{
    std::string header = StringHelpers::Trim(headerNode->Inner());
    if (header.empty())
    {
        return false;
    }

    m_header.Parsed = true;
    m_header.Value = header;

    return true;
}

