std::string SuperEnumConverter::PrintEnumConverter(int indents)
{
    if (m_converterType == SuperEnumConverterType::Standard)
    {
        return PrintEnumConverterStandard(indents);
    }
    else if (m_converterType == SuperEnumConverterType::BitFlag)
    {
        return PrintEnumConverterBitflag(indents);
    }

    Log::Error("The enum converter type is not supported. "
        "Please create an implementation for: " + ESuperEnumConverterType::ToString(m_converterType),
        "SuperEnumConverter::PrintEnumConverter(int)");
    return PrintEnumConverterStandard(indents);
}

std::string SuperEnumConverter::PrintEnumConverterStandard(int indents)
{
    std::string output = {};

    // Comment
    if (m_enumComment.Parsed)
    {
        output += PrintSingleComment(m_enumComment.Value, indents);
    }
    else
    {
        std::string generatedComment = "Converts between " + m_left.Type + " and " + m_right.Type;
        output += PrintSingleComment(generatedComment, indents);
    }

    // Class open
    output += PrintIndents(indents) + "class " + m_enumConverterName.Value + "\n";
    output += PrintIndents(indents) + "{\n";
    output += PrintIndents(indents) + "public:\n";
    ++indents;

    output += PrintIndents(indents) + "/// <summary>\n";
    output += PrintIndents(indents) + "/// Converts from the enum " + PrintEnumPrefixIfAny(false) + m_right.Type + " to " + PrintEnumPrefixIfAny(true) + m_left.Type + "\n";
    output += PrintIndents(indents) + "/// </summary>\n";
        
    output += PrintIndents(indents) + "static " + m_left.Type + " Convert(" + m_right.Type + " input)\n";
    output += PrintIndents(indents) + "{\n";
    ++indents;
        output += PrintIndents(indents) + "switch(input)\n";
        output += PrintIndents(indents) + "{\n";
        ++indents;
        for (const std::shared_ptr<Conversion>& conversion : m_allConversions)
        {
            output += PrintIndents(indents) + "case " + PrintEnumPrefixIfAny(false) +  conversion->Right + ": return " + PrintEnumPrefixIfAny(true) + conversion->Left + ";\n";
        }
        if (m_defaultValue)
        {
            output += PrintIndents(indents) + "default: return " + PrintEnumPrefixIfAny(true) + m_defaultValue->Left + ";\n";
        }
        --indents;
        output += PrintIndents(indents) + "}\n";

    // Consider adding a log in the cases where default is used.
    if (!m_defaultValue)
    {
        output += "\n" + PrintIndents(indents) + "return " + PrintEnumPrefixIfAny(true) + m_allConversions.at(0)->Left + ";\n";
    }
    --indents;
    output += PrintIndents(indents) + "}\n";

    // Then do the reverse.
    output += PrintIndents(indents) + "\n";
    output += PrintIndents(indents) + "/// <summary>\n";
    output += PrintIndents(indents) + "/// Converts from the enum " + PrintEnumPrefixIfAny(true) + m_left.Type + " to " + PrintEnumPrefixIfAny(false) + m_right.Type + "\n";
    output += PrintIndents(indents) + "/// </summary>\n";
    output += PrintIndents(indents) + "static " + m_right.Type + " Convert(" + m_left.Type + " input)\n";
    output += PrintIndents(indents) + "{\n";
    ++indents;
    output += PrintIndents(indents) + "switch(input)\n";
    output += PrintIndents(indents) + "{\n";
    ++indents;
    for (const std::shared_ptr<Conversion>& conversion : m_allConversions)
    {
        output += PrintIndents(indents) + "case " + PrintEnumPrefixIfAny(true) + conversion->Left + ": return " + PrintEnumPrefixIfAny(false) + conversion->Right + ";\n";
    }
    if (m_defaultValue)
    {
        output += PrintIndents(indents) + "default: return " + PrintEnumPrefixIfAny(false) + m_defaultValue->Right + ";\n";
    }
    --indents;
    output += PrintIndents(indents) + "}\n";

    // Consider adding a log in the cases where default is used.
    if (!m_defaultValue)
    {
        output += "\n" + PrintIndents(indents) + "return " + PrintEnumPrefixIfAny(false) + m_allConversions.at(0)->Right + ";\n";
    }
    --indents;
    output += PrintIndents(indents) + "}\n";

    // Class close
    --indents;
    output += PrintIndents(indents) + "};\n";
    return output;
}

